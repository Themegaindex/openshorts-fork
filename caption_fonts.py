# Characters that do not resolve to the table come from a fallback font.
# Wide East Asian characters and emoji get about one font size at most
# (measured: 0.73). Letters of other scripts measured at most 0.62 (Arabic
# 0.36; Hebrew, Devanagari, Thai, Georgian 0.49; Armenian 0.62).
WIDE_CHARACTER_WIDTH = 1.0
UNKNOWN_LETTER_WIDTH = 0.75
_ZERO_WIDTH_CATEGORIES = ("Mn", "Me", "Cf")


def _fallback_width(char):
    if unicodedata.category(char) in _ZERO_WIDTH_CATEGORIES:
        return 0.0
    if unicodedata.east_asian_width(char) in ("W", "F") or unicodedata.category(char) in ("So", "Co", "Cs"):
        return WIDE_CHARACTER_WIDTH
    return UNKNOWN_LETTER_WIDTH


# Scripts whose letters join or stack into one shape, or that run right to
# left: a word in them must never be cut between two characters.
_UNSPLITTABLE_RANGES = (
    (0x0590, 0x08FF),   # Hebrew, Arabic, Syriac, Arabic Supplement, Thaana, N'Ko, Samaritan, Mandaic
    (0x0900, 0x0DFF),   # Devanagari ... Malayalam, Sinhala
    (0x0E00, 0x0FFF),   # Thai, Lao, Tibetan
    (0x1000, 0x109F),   # Myanmar
    (0x1780, 0x18AF),   # Khmer, Mongolian
    (0xA8E0, 0xA8FF),   # Devanagari Extended
    (0xFB1D, 0xFDFF),   # Hebrew and Arabic presentation forms
    (0xFE70, 0xFEFF),   # Arabic presentation forms B
)


def can_split(text):
    """False when ``text`` contains a script whose words must stay whole."""
    return not any(
        low <= ord(char) <= high for char in str(text) for low, high in _UNSPLITTABLE_RANGES
    )


def _family_key(font_name):
    return " ".join(str(font_name or "").lower().split())


def _faces_for(family, platform):
    if platform == "win32":
        faces = _WINDOWS_FACES.get(family)
        return faces or tuple(_FACE_WIDTHS)
    if family in _DOCKER_FACES:
        return _DOCKER_FACES[family] + _WINDOWS_FACES[family]
    return tuple(_FACE_WIDTHS)


@lru_cache(maxsize=64)
def _widths(family, platform):
    faces = _faces_for(family, platform)
    return {
        char: max(_FACE_WIDTHS[face][index] for face in faces) / 1000.0
        for index, char in enumerate(_CHARSET)
    }


@lru_cache(maxsize=4096)
def _table_character(char):
    """The listed character that stands in for ``char``, or None."""
    if char in _CHARACTER_INDEX:
        return char
    parts = unicodedata.normalize("NFD", char)
    # Drop combining marks from the end; a mark that changes the width (the
    # Vietnamese horn) stays as long as its precomposed letter is listed.
    while len(parts) > 1:
        parts = parts[:-1]
        if not all(unicodedata.combining(mark) for mark in parts[1:]):
            break
        candidate = unicodedata.normalize("NFC", parts)
        if candidate in _CHARACTER_INDEX:
            return candidate
    return None


_CHARACTER_INDEX = {char: index for index, char in enumerate(_CHARSET)}


def text_width(text, font_name, platform=None):
    """Width of ``text`` in units of the ASS font size, as libass lays it out
    in ``font_name`` (bold), on ``platform`` (default: this machine)."""
    widths = _widths(_family_key(font_name), platform or sys.platform)
    total = 0.0
    for char in str(text):
        if unicodedata.combining(char):
            continue   # a combining mark sits on the letter before it
        listed = _table_character(char)
        total += widths[listed] if listed is not None else _fallback_width(char)
    return total
