"""Regenerate the advance-width table in caption_fonts.py.

Developer tool, not part of the app: nothing in the app imports it, and the
app does not need fontTools at run time.

What it needs:
  * fontTools (``pip install fonttools``; it also comes with matplotlib),
  * the Windows fonts in C:\\Windows\\Fonts (verdanab, arialbd, ariblk, impact,
    georgiab, courbd) - run it on Windows,
  * DejaVuSans-Bold.ttf and DejaVuSerif-Bold.ttf, the faces the Docker image
    uses (docker/fonts.conf). By default they are taken from matplotlib's
    bundled fonts; --dejavu-dir points elsewhere.

How to regenerate:
  python tools/caption_font_widths.py            # print the table block
  python tools/caption_font_widths.py --write    # replace it in caption_fonts.py

The block between the two marker lines in caption_fonts.py is replaced, the
rest of the file stays as it is. Widths are advance / (usWinAscent +
usWinDescent), the unit libass sizes a face by, rounded up to thousandths.
A face without a glyph for a character gets the widest width another face
has for it, because libass then draws a fallback font.
"""
import argparse
import math
import os
import sys
import textwrap

BEGIN = "# --- generated by tools/caption_font_widths.py, do not edit by hand ---"
END = "# --- end of generated table ---"
TARGET = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "caption_fonts.py")

WINDOWS_FONTS = os.path.join(os.environ.get("WINDIR", r"C:\Windows"), "Fonts")
FACES = (
    ("verdana_bold", "windows", "verdanab.ttf"),
    ("arial_bold", "windows", "arialbd.ttf"),
    ("arial_black", "windows", "ariblk.ttf"),
    ("impact", "windows", "impact.ttf"),
    ("georgia_bold", "windows", "georgiab.ttf"),
    ("courier_new_bold", "windows", "courbd.ttf"),
    ("dejavu_sans_bold", "dejavu", "DejaVuSans-Bold.ttf"),
    ("dejavu_serif_bold", "dejavu", "DejaVuSerif-Bold.ttf"),
)

# Printable ASCII, every Latin-1 and Latin Extended-A letter (Western, Central
# and Eastern European languages, Turkish), the Vietnamese horn letters whose
# horn makes them wider than their base, Greek and Cyrillic (the translation
# targets Greek, Russian, Ukrainian, Bulgarian), and common punctuation.
# Other accented letters are measured by their base letter in caption_fonts.
CHARSET = (
    "".join(chr(code) for code in range(0x20, 0x7F))
    + "".join(chr(code) for code in range(0xC0, 0x100) if code not in (0xD7, 0xF7))
    + "".join(chr(code) for code in range(0x100, 0x180))
    + "ƠơƯư"
    + "".join(chr(code) for code in range(0x386, 0x3CF) if code not in (0x387, 0x38B, 0x38D, 0x3A2))
    + "".join(chr(code) for code in range(0x400, 0x460))
    + "Ґґ"
    + "‘’‚“”„–—…«»¿¡€"
)


def _dejavu_dir(explicit):
    if explicit:
        return explicit
    import matplotlib
    return os.path.join(os.path.dirname(matplotlib.__file__), "mpl-data", "fonts", "ttf")


def measure(dejavu_dir):
    from fontTools.ttLib import TTFont

    raw = {}
    sizes = {}
    for name, origin, filename in FACES:
        path = os.path.join(WINDOWS_FONTS if origin == "windows" else dejavu_dir, filename)
        font = TTFont(path)
        os2 = font["OS/2"]
        size_units = os2.usWinAscent + os2.usWinDescent
        cmap = font.getBestCmap()
        advances = font["hmtx"].metrics
        raw[name] = [
            advances[cmap[ord(char)]][0] / size_units if ord(char) in cmap else None
            for char in CHARSET
        ]
        sizes[name] = (filename, os2.usWinAscent, os2.usWinDescent)
    widest = [max(raw[name][index] or 0.0 for name in raw) for index in range(len(CHARSET))]
    table = {
        name: [math.ceil((width if width is not None else widest[index]) * 1000 - 1e-9)
               for index, width in enumerate(widths)]
        for name, widths in raw.items()
    }
    missing = {name: "".join(CHARSET[i] for i, w in enumerate(widths) if w is None)
               for name, widths in raw.items()}
    return table, sizes, missing


def render_block(table, sizes):
    lines = [BEGIN, f"_CHARSET = {CHARSET!r}", "", "_FACE_WIDTHS = {"]
    for name, values in table.items():
        filename, ascent, descent = sizes[name]
        lines.append(f"    # {filename}: usWinAscent {ascent} + usWinDescent {descent}")
        lines.append(f"    {name!r}: (")
        lines.extend(f"        {chunk}" for chunk in textwrap.wrap(", ".join(map(str, values)), width=88))
        lines.append("    ),")
    lines += ["}", END]
    return "\n".join(lines) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--write", action="store_true", help="replace the table in caption_fonts.py")
    parser.add_argument("--dejavu-dir", help="folder with DejaVuSans-Bold.ttf and DejaVuSerif-Bold.ttf")
    args = parser.parse_args(argv)

    table, sizes, missing = measure(_dejavu_dir(args.dejavu_dir))
    block = render_block(table, sizes)
    for name, chars in missing.items():
        if chars:
            print(f"{name}: no glyph for {chars!r}, using the widest face", file=sys.stderr)
    if not args.write:
        sys.stdout.write(block)
        return 0
    with open(TARGET, encoding="utf-8") as handle:
        source = handle.read()
    start, end = source.index(BEGIN), source.index(END) + len(END) + 1
    with open(TARGET, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(source[:start] + block + source[end:])
    print(f"{len(CHARSET)} characters x {len(table)} faces written to {TARGET}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
